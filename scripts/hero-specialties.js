const container = document.getElementById("container");

function display(){

    categories.forEach(line => {

        var filteredheroes = heroes.filter(hero => hero.specialties.includes(line.name));

        var categContainer = document.createElement("div");

        categContainer.classList.add("categ", "reveal");

        categContainer.innerHTML = 
        `
        <p class="specialty">
         ${line.name}
        </p>
        <p class="explanation">
         ${line.description}
        </p>
        <div id="image-div">
         ${filteredheroes.map(hero => 
                `
                <div class="img-txt">
                    <img class="reveal" src="images/pages/hero-icons/${hero.name.toLowerCase()}.webp" alt="">
                    <p class="reveal">${hero.name}</p>
                </div>`).join("")}
        </div>
        <div class="fancy-line"></div>
        `
        container.append(categContainer);
    })

}

